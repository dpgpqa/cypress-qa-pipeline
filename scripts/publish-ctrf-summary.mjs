/**
 * Publish CTRF test summary to GitHub Actions Job Summary ($GITHUB_STEP_SUMMARY).
 * Reads a CTRF JSON report and renders a Markdown summary table.
 */

import { readFileSync, existsSync } from 'fs';

const reportPath = process.argv[2] || 'ctrf/ctrf-report.json';
const suiteTitle = process.argv[3] || 'Test Suite';

const summaryFile = process.env.GITHUB_STEP_SUMMARY;

if (!summaryFile) {
  console.log('GITHUB_STEP_SUMMARY not set — skipping summary publish');
  process.exit(0);
}

if (!existsSync(reportPath)) {
  const msg = `### ⚠️ ${suiteTitle} — CTRF report not found\n\nNo CTRF report was generated at \`${reportPath}\`.\n`;
  require('fs').appendFileSync(summaryFile, msg);
  process.exit(0);
}

let report;
try {
  report = JSON.parse(readFileSync(reportPath, 'utf8'));
} catch (err) {
  const msg = `### ❌ ${suiteTitle} — Failed to parse CTRF report\n\n\`${err.message}\`\n`;
  require('fs').appendFileSync(summaryFile, msg);
  process.exit(0);
}

// CTRF report structure (common shape)
const results = report.results || report.tests || [];
const total = results.length || report.stats?.total || 0;
const passed = results.filter((r) => r.status === 'passed').length || report.stats?.passed || 0;
const failed = results.filter((r) => r.status === 'failed').length || report.stats?.failed || 0;
const skipped = results.filter((r) => r.status === 'skipped').length || report.stats?.skipped || 0;
const duration = report.stats?.duration || report.totalDuration || 0;

const passRate = total > 0 ? ((passed / total) * 100).toFixed(1) : '0.0';
const statusIcon = failed > 0 ? '❌' : passed > 0 ? '✅' : '⚪';

let md = `
### ${statusIcon} ${suiteTitle} — Test Results

| Metric | Value |
|--------|-------|
| Total Tests | ${total} |
| Passed | ${passed} |
| Failed | ${failed} |
| Skipped | ${skipped} |
| Pass Rate | ${passRate}% |
| Duration (ms) | ${duration} |

`;

if (failed > 0 && results.length > 0) {
  md += '### ❌ Failed Tests\n\n';
  results
    .filter((r) => r.status === 'failed')
    .slice(0, 10)
    .forEach((r) => {
      md += `- **${r.name || r.title || 'Unknown test'}**\n`;
      if (r.error) {
        md += `  - Error: \`${r.error.message || r.error || ''}\`\n`;
      }
      if (r.stack) {
        md += `  - Stack: \`\`\`\n${r.stack.slice(0, 500)}\n\`\`\`\n`;
      }
    });
  if (results.filter((r) => r.status === 'failed').length > 10) {
    md += `- ... and ${results.filter((r) => r.status === 'failed').length - 10} more failures\n`;
  }
}

md += `---\n*Report generated by [CTRF](https://github.com/cypress-ctrf/json-reporter)*\n`;

require('fs').appendFileSync(summaryFile, md);
console.log(`CTRF summary published for ${suiteTitle}: ${passed}/${total} passed`);
